interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  currentLanguageOption: LanguageOption;
  t: (key: string, fallback?: string) => string;
  translateAmenity: (name: string) => string;
  translateStyle: (name: string) => string;
  translateModel: (name: string) => string;
  translateMood: (mood: string) => string;
  translateCity: (city: string) => string;
  translateShop: (shop: CoffeeShop) => CoffeeShop;
  translateMenuItem: (item: MenuItem) => MenuItem;
  isLanguageModalOpen: boolean;
  setIsLanguageModalOpen: (open: boolean) => void;
  openLanguageModal: () => void;
  closeLanguageModal: () => void;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'en',
  setLanguage: () => {},
  currentLanguageOption: SUPPORTED_LANGUAGES[2],
  t: (key: string, fallback?: string) => fallback || key,
  translateAmenity: (name: string) => name,
  translateStyle: (name: string) => name,
  translateModel: (name: string) => name,
  translateMood: (mood: string) => mood,
  translateCity: (city: string) => city,
  translateShop: (shop: CoffeeShop) => shop,
  translateMenuItem: (item: MenuItem) => item,
  isLanguageModalOpen: false,
  setIsLanguageModalOpen: () => {},
  openLanguageModal: () => {},
  closeLanguageModal: () => {},
});

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    const saved = localStorage.getItem('app_language') as Language;
    if (saved && ['zh-TW', 'th', 'en', 'vi'].includes(saved)) {
      return saved;
    }
    return 'en'; // default to English or user's requested languages
  });

  const [isLanguageModalOpen, setIsLanguageModalOpen] = useState<boolean>(false);

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem('app_language', lang);
  };

  const currentLanguageOption = 
    SUPPORTED_LANGUAGES.find(l => l.code === language) || SUPPORTED_LANGUAGES[2];

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language];
    if (langDict && langDict[key]) {
      return langDict[key];
    }
    // Fallback to English, then Vietnamese, then fallback param or key
    if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
      return TRANSLATIONS['en'][key];
    }
    if (TRANSLATIONS['vi'] && TRANSLATIONS['vi'][key]) {
      return TRANSLATIONS['vi'][key];
    }
    return fallback || key;
  };

  const translateAmenity = (name: string): string => {
    return AMENITY_TRANSLATIONS[language]?.[name] || AMENITY_TRANSLATIONS['en']?.[name] || name;
  };

  const translateStyle = (name: string): string => {
    return STYLE_TRANSLATIONS[language]?.[name] || STYLE_TRANSLATIONS['en']?.[name] || name;
  };

  const translateModel = (name: string): string => {
    return SPECIAL_MODEL_TRANSLATIONS[language]?.[name] || SPECIAL_MODEL_TRANSLATIONS['en']?.[name] || name;
  };

  const translateMood = (mood: string): string => {
    return MOOD_TRANSLATIONS[language]?.[mood] || MOOD_TRANSLATIONS['en']?.[mood] || mood;
  };

  const translateCity = (city: string): string => {
    return CITY_TRANSLATIONS[language]?.[city] || CITY_TRANSLATIONS['en']?.[city] || city;
  };

  const translateShop = (shop: CoffeeShop): CoffeeShop => {
    if (!shop) return shop;
    const shopId = String(shop.id || '');
    const localizedData = SHOP_TRANSLATIONS[language]?.[shopId] || SHOP_TRANSLATIONS['en']?.[shopId];
    
    if (!localizedData) {
      return {
        ...shop,
        primaryModel: shop.primaryModel ? ((SPECIAL_MODEL_TRANSLATIONS[language]?.[shop.primaryModel] || shop.primaryModel) as SpecialModel) : undefined,
        primaryStyle: shop.primaryStyle ? ((STYLE_TRANSLATIONS[language]?.[shop.primaryStyle] || shop.primaryStyle) as ShopStyle) : undefined,
      };
    }

    return {
      ...shop,
      name: localizedData.name || shop.name,
      address: localizedData.address || shop.address,
      tags: localizedData.tags || shop.tags,
      primaryModel: shop.primaryModel ? ((SPECIAL_MODEL_TRANSLATIONS[language]?.[shop.primaryModel] || shop.primaryModel) as SpecialModel) : undefined,
      primaryStyle: shop.primaryStyle ? ((STYLE_TRANSLATIONS[language]?.[shop.primaryStyle] || shop.primaryStyle) as ShopStyle) : undefined,
      aiIntel: localizedData.summary ? {
        ...(shop.aiIntel as any),
        summary: localizedData.summary || shop.aiIntel?.summary || '',
        vibe: localizedData.vibe || shop.aiIntel?.vibe || '',
        bestFor: localizedData.bestFor || shop.aiIntel?.bestFor || [],
        aiReviewSynthesis: {
          pros: localizedData.pros || shop.aiIntel?.aiReviewSynthesis?.pros || [],
          tips: localizedData.tips || shop.aiIntel?.aiReviewSynthesis?.tips || '',
          cons: (shop.aiIntel?.aiReviewSynthesis as any)?.cons
        },
        workAndTech: localizedData.workAndTech ? {
          ...shop.aiIntel?.workAndTech,
          ...localizedData.workAndTech
        } : shop.aiIntel?.workAndTech,
        googleMapsData: shop.aiIntel?.googleMapsData ? {
          ...shop.aiIntel.googleMapsData,
          fullAddress: localizedData.fullAddress || shop.aiIntel.googleMapsData.fullAddress,
          parkingInfo: localizedData.parkingInfo || shop.aiIntel.googleMapsData.parkingInfo,
          hoursSummary: localizedData.hoursSummary || shop.aiIntel.googleMapsData.hoursSummary
        } : undefined
      } : shop.aiIntel
    };
  };

  const translateMenuItem = (item: MenuItem): MenuItem => {
    if (!item) return item;
    const itemId = String(item.id || '');
    const localizedMenu = MENU_TRANSLATIONS[language]?.[itemId] || MENU_TRANSLATIONS['en']?.[itemId];
    if (!localizedMenu) return item;
    return {
      ...item,
      name: localizedMenu.name || item.name,
      description: localizedMenu.description || item.description,
      category: (localizedMenu.category as any) || item.category
    };
  };

  const openLanguageModal = () => setIsLanguageModalOpen(true);
  const closeLanguageModal = () => setIsLanguageModalOpen(false);

  return (
    <LanguageContext.Provider value={{
      language,
      setLanguage,
      currentLanguageOption,
      t,
      translateAmenity,
      translateStyle,
      translateModel,
      translateMood,
      translateCity,
      translateShop,
      translateMenuItem,
      isLanguageModalOpen,
      setIsLanguageModalOpen,
      openLanguageModal,
      closeLanguageModal
    }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
